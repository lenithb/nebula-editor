export type Lang = "en" | "es";

function detectLang(): Lang {
  const langs =
    navigator.languages && navigator.languages.length > 0
      ? navigator.languages
      : [navigator.language ?? ""];
  return langs.some((l) => l.toLowerCase().startsWith("es")) ? "es" : "en";
}

export const lang: Lang = detectLang();

